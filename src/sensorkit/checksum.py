"""Checksums used on sensor data frames."""


def crc16_ccitt(data, crc=0xFFFF):
    """CRC-16/CCITT-FALSE over a bytes-like object."""
    for byte in data:
        crc ^= byte << 8
        for _ in range(8):
            if crc & 0x8000:
                crc = ((crc << 1) ^ 0x1021) & 0xFFFF
            else:
                crc = (crc << 1) & 0xFFFF
    return crc


def crc32(data):
    """CRC-32 (IEEE 802.3, reflected) over a bytes-like object."""
    crc = 0xFFFFFFFF
    for byte in data:
        crc ^= byte
        for _ in range(8):
            if crc & 1:
                crc = (crc >> 1) ^ 0xEDB88320
            else:
                crc >>= 1
    return crc ^ 0xFFFFFFFF
